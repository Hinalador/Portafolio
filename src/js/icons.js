export function icon(name, cls = 'size-5') {
  const p = paths[name];
  if (!p) return '';
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" class="${cls}" aria-hidden="true" focusable="false">${p}</svg>`;
}

/** Reemplaza cada elemento con [data-icon] por su SVG correspondiente. */
export function hydrateIcons(root = document) {
  root.querySelectorAll('[data-icon]').forEach((el) => {
    el.innerHTML = icon(el.dataset.icon, el.dataset.iconClass || 'size-5');
  });
}
